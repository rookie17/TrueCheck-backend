@app.route("/get-product-details", methods=["GET"])
def get_product_details():
    barcode = request.args.get("barcode")
    if not barcode:
        return jsonify({"error": "No barcode provided"}), 400

    product_data = get_product_from_db(barcode)
    if product_data:
        return jsonify({
            "product_name":    product_data.get("product_name", "Unknown"),
            "ingredients":     product_data.get("ingredients", []),
            "nutrients_per_100g": product_data.get("nutrients_per_100g", {}),
        })

    url      = f"https://world.openfoodfacts.org/api/v0/product/{barcode}.json"
    response = requests.get(url, timeout=10)
    if response.status_code != 200:
        return jsonify({"error": "Failed to fetch from OpenFoodFacts"}), 500

    product      = response.json().get("product", {})
    product_name = product.get("product_name", "Unknown")
    ingredients  = [i.get("text") for i in product.get("ingredients", []) if "text" in i]
    nutriments   = product.get("nutriments", {})
    nutrition    = {k: v for k, v in nutriments.items() if k.endswith("_100g")}

    save_product_to_db(barcode, product_name, ingredients, nutrition)

    return jsonify({
        "product_name":       product_name,
        "ingredients":        ingredients,
        "nutrients_per_100g": nutrition,
    })


@app.route("/get-ingredients", methods=["GET"])
def get_ingredients():
    barcode = request.args.get("barcode")
    if not barcode:
        return jsonify({"error": "No barcode provided"}), 400

    product_data = get_product_from_db(barcode)
    if product_data:
        return jsonify({
            "product_name": product_data["product_name"],
            "ingredients":  product_data.get("ingredients", []),
        })

    url      = f"https://world.openfoodfacts.org/api/v0/product/{barcode}.json"
    response = requests.get(url, timeout=10)
    if response.status_code != 200:
        return jsonify({"error": "Failed to fetch from OpenFoodFacts"}), 500

    product      = response.json().get("product", {})
    product_name = product.get("product_name", "Unknown")
    ingredients  = [i.get("text") for i in product.get("ingredients", []) if "text" in i]

    if not ingredients:
        return jsonify({
            "product_name": product_name,
            "ingredients":  [],
            "note": "No ingredients found for this barcode on OpenFoodFacts.",
        })

    save_product_to_db(barcode, product_name, ingredients)
    return jsonify({"product_name": product_name, "ingredients": ingredients})


@app.route("/get-overall-product-rating", methods=["GET"])
def get_overall_product_rating():
    barcode = request.args.get("barcode")
    if not barcode:
        return jsonify({"error": "No barcode provided"}), 400

    product_data = get_product_from_db(barcode)
    if not product_data:
        return jsonify({"error": "Product not found in DB"}), 404

    ingredient_names = _flatten_ingredients(product_data.get("ingredients", []))
    if not ingredient_names:
        return jsonify({"error": "No ingredients found. Scan product first."}), 400

    final_ingredient_list = [
        {"name": n, "profile": get_ingredient_profile_from_db(n) or _build_ingredient_profile_fallback(n)}
        for n in ingredient_names
    ]
    percent_estimates = get_percent_estimates(barcode, ingredient_names)
    nutrition_data    = product_data.get("nutrients_per_100g", {})

    product_for_scoring = {
        "ingredients":        ingredient_names,
        "nutrients_per_100g": nutrition_data,
    }
    rating_response = _compute_rating(product_for_scoring, final_ingredient_list, percent_estimates)

    raw_rating_to_store = {
        "overall_score": rating_response["overall_score"],
        "method":        rating_response["method"],
        "confidence":    rating_response.get("confidence", "medium"),
        "breakdown":     rating_response.get("breakdown", {}),
    }
    save_product_rating_to_db(barcode, raw_rating_to_store)

    return jsonify(rating_response)


