@app.route("/model-info", methods=["GET"])
def model_info():
    if ANALYSIS_MODE != "ml":
        return jsonify({"message": "model-info is only available in ML mode."}), 200
    meta = get_model_metadata()
    if meta:
        return jsonify(meta)
    return jsonify({
        "status":  "no model trained yet",
        "message": "Run: python -m ml.train",
    }), 404


@app.route("/retrain", methods=["POST"])
def retrain():
    if ANALYSIS_MODE != "ml":
        return jsonify({"message": "Retrain is only available in ML mode."}), 200
    try:
        from ml.train import train
        from ml.predict import _load_model
        result = train()
        _load_model()
        return jsonify({"status": "ok", "result": str(result)})
    except Exception as e:
        logger.exception("Manual retrain failed")
        return jsonify({"error": str(e)}), 500


