# ─── Helpers ──────────────────────────────────────────────────────────────────

def _flatten_ingredients(raw_list: list) -> list[str]:
    """Normalise a mixed list of strings / dicts to plain lowercase strings."""
    result = []
    for item in raw_list:
        if isinstance(item, dict):
            name = item.get("text") or item.get("name") or ""
        else:
            name = str(item)
        name = name.strip().lower()
        if name:
            result.append(name)
    return result


def _build_ingredient_profile_fallback(name: str) -> dict:
    """
    Rule-based ingredient profile matching the Gemini/Groq Firestore shape.
    Used in ML mode (no LLM calls) and as a fallback if Groq fails.
    """
    return {
        "ingredient_name": name,
        "ingredient_profile": {
            "health_score":      5,
            "pros":              [],
            "cons":              [],
            "allergen":          "unknown",
            "regulatory_status": "unknown",
            "category":          "other",
            "health_flag":       "unknown",
            "source":            "rule_based",
            "description":       "",
            "dietary_tags":      [],
            "flags":             [],
            "processing_level":  "unknown",
            "why_this_score":    "No profile available — rule-based fallback.",
        },
    }


def _fix_nested_profile(profile: dict) -> dict:
    """Fix double-nested ingredient profiles from old Gemini saves in Firestore."""
    if not profile:
        return profile
    inner = profile.get("ingredient_profile", {})
    if isinstance(inner, dict) and "ingredient_profile" in inner:
        profile["ingredient_profile"] = inner["ingredient_profile"]
    return profile


def _build_ml_rating_response(rating: dict) -> dict:
    """
    Wraps ML predict_score output into the dual schema:
      - Old frontend keys: product_score, processing_level, pros, cons
      - New ML keys:       overall_score, method, confidence, breakdown
    """
    score      = rating.get("overall_score", 0)
    breakdown  = rating.get("breakdown", {})
    method     = rating.get("method", "rule_based")
    confidence = rating.get("confidence", "medium")

    grade = _score_to_grade(score)

    return {
        # Old keys — frontend keeps working without changes
        "product_score":    round(score, 2),
        "processing_level": grade,
        "why_this_score":   (
            f"Score generated by ML model (method: {method}, confidence: {confidence})."
        ),
        "pros":             breakdown.get("positives", []),
        "cons":             breakdown.get("negatives", []),
        "dietary_tags":     [],

        # New ML keys
        "overall_score":    round(score, 2),
        "method":           method,
        "confidence":       confidence,
        "breakdown":        breakdown,
    }


def _build_groq_rating_response(rating: dict) -> dict:
    """
    Wraps Groq LLM rating output into the same dual schema.
    Groq returns: { product_score, processing_level, pros, cons,
                    why_this_score, dietary_tags, ... }
    """
    if "error" in rating:
        logger.warning("Groq rating error: %s", rating["error"])
        # Degrade gracefully to a neutral score
        return _build_ml_rating_response({"overall_score": 5.0, "method": "groq_error"})

    score = float(rating.get("product_score", rating.get("overall_score", 5.0)))

    return {
        # Old keys
        "product_score":    round(score, 2),
        "processing_level": rating.get("processing_level", _score_to_grade(score)),
        "why_this_score":   rating.get("why_this_score", ""),
        "pros":             rating.get("pros", []),
        "cons":             rating.get("cons", []),
        "dietary_tags":     rating.get("dietary_tags", []),

        # New keys — normalised so both modes share the same shape
        "overall_score":    round(score, 2),
        "method":           "groq",
        "confidence":       "high",
        "breakdown":        {
            "positives": rating.get("pros", []),
            "negatives": rating.get("cons", []),
        },
    }


def _score_to_grade(score: float) -> str:
    if score >= 8:   return "A"
    if score >= 6:   return "B"
    if score >= 4:   return "C"
    if score >= 2:   return "D"
    return "F"


# ─── Mode-aware scoring functions ─────────────────────────────────────────────

def _fetch_ingredient_profile(name: str) -> dict:
    """
    Returns a Firestore-ready profile dict.
    Groq mode  → LLM call → fallback on error
    ML mode    → rule-based fallback (profiles stored for consistency)
    """
    if ANALYSIS_MODE == "groq":
        try:
            llm_profile = get_ingredient_profile_from_llm(name)
            if llm_profile and "error" not in llm_profile:
                full_doc = {
                    "ingredient_name":    name,
                    "ingredient_profile": llm_profile,
                }
                save_ingredient_to_db(name, full_doc)
                return full_doc
        except Exception as e:
            logger.warning("Groq ingredient profile failed for '%s': %s", name, e)

    # ML mode or Groq fallback
    profile = _build_ingredient_profile_fallback(name)
    save_ingredient_to_db(name, profile)
    return profile


def _compute_rating(product_for_scoring: dict, final_ingredient_list: list,
                    percent_estimates: list) -> dict:
    """
    Returns the dual-schema rating dict.
    Groq mode → LLM call
    ML mode   → local GradientBoosting
    """
    if ANALYSIS_MODE == "groq":
        raw = get_product_rating_from_llm(final_ingredient_list, percent_estimates)
        return _build_groq_rating_response(raw)
    else:
        raw = predict_score(product_for_scoring)
        return _build_ml_rating_response(raw)


